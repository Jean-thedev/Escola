public class Professor {
    private String nome;
    private String area;

     //vetor
     
    public Professor(String nome, String area) {
        this.nome = nome;
        this.area = area;
    }
    public String getNome() {
        return nome;
    }
    public void setNome(String nome) {
        this.nome = nome;
    }
    public String getArea() {
        return area;
    }
    public void setArea(String area) {
        this.area = area;
    }

   

    





}
